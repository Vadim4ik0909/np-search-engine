  // 5.1. РОЗПІЗНАВАННЯ МІСТА (Точне O(1) або нечітке Levenshtein Distance <= 2)
  function findSettlementByNameOrFuzzy(word, contextOblast, contextRaion) {
    if (!word || word.length < 2) return null;
    const w = word.toLowerCase().trim();
    if (isOblastToken(w) && w !== 'дніпро') return null;
    const wNorm = normalizeLocativeCase(w);

    // 1. Точний збіг назви або аліасу у пріоритетному словнику UKRAINE_SETTLEMENTS (185 міст) - O(1)
    const exactBase = _settlementsByName.get(w) || _settlementsByName.get(wNorm) ||
                      _settlementsByAlias.get(w) || _settlementsByAlias.get(wNorm);
    if (exactBase) {
      return exactBase;
    }

    // 2. Точний збіг у повному реєстрі ALL_SETTLEMENTS (26 000+ сіл, смт, селищ, міст) - O(1)
    const candidates = _allSettlementsByName.get(w) || _allSettlementsByName.get(wNorm);
    if (candidates && candidates.length > 0) {
      let chosen = candidates[0];
      if (candidates.length > 1 && (contextOblast || contextRaion)) {
        const cObl = (contextOblast || '').toLowerCase();
        const cRaion = (contextRaion || '').toLowerCase();
        for (let i = 0; i < candidates.length; i++) {
          const cand = candidates[i];
          const candObl = (cand.oblast || '').toLowerCase();
          const candRaion = (cand.raion || '').toLowerCase();
          if (cObl && (candObl.includes(cObl) || cObl.includes(candObl))) {
            chosen = cand;
            break;
          }
          if (cRaion && (candRaion.includes(cRaion) || cRaion.includes(candRaion))) {
            chosen = cand;
            break;
          }
        }
      }
      return {
        name: chosen.cleanName,
        oblast: chosen.oblast,
        raion: chosen.raion,
        type: chosen.type || 'село',
        allVariants: candidates
      };
    }

    // 3. Нечітке зіставлення (Levenshtein Distance <= 2):
    // Згідно з правилом js-memory-perf-optimizer:
    // НЕ проганяти 26k населених пунктів через важкі цикли!
    // Нечіткий пошук виконується ВИКЛЮЧНО по UKRAINE_SETTLEMENTS (185 міст)
    // Захист: точний збіг назви населеного пункту має абсолютний пріоритет над префіксами довших назв.
    // Заборонено замінювати точну назву "Славута" на "Славутич" тощо.
    if (w.length >= 4) {
      const maxAllowedDist = w.length >= 5 ? 2 : 1;
      let bestMatch = null;
      let minDistance = 999;

      for (let s of UKRAINE_SETTLEMENTS) {
        const sLower = s.name.toLowerCase();
        // Якщо одне слово є префіксом іншого і вони мають різну довжину з різними закінченнями/суфіксами (наприклад, славута vs славутич), не підміняти!
        if (Math.abs(w.length - sLower.length) > 1 && (sLower.startsWith(w) || w.startsWith(sLower))) {
          continue;
        }

        const d1 = damerauLevenshtein(w, sLower);
        const d2 = damerauLevenshtein(wNorm, sLower);
        const d = Math.min(d1, d2);
        if (d <= maxAllowedDist && d < minDistance) {
          minDistance = d;
          bestMatch = s;
        }

        if (s.aliases) {
          for (let alias of s.aliases) {
            if (Math.abs(w.length - alias.length) > 1 && (alias.startsWith(w) || w.startsWith(alias))) {
              continue;
            }
            const da = damerauLevenshtein(w, alias);
            if (da <= maxAllowedDist && da < minDistance) {
              minDistance = da;
              bestMatch = s;
            }
          }
        }
      }

      if (bestMatch) {
        return bestMatch;
      }
    }

    return null;
  }

  // 5.2. ІНТЕЛЕКТУАЛЬНА НОРМАЛІЗАЦІЯ ПОШУКОВОГО ЗАПИТУ (Smart Spellcheck & Fuzzy Normalization)
  function normalizeSearchTokens(rawQuery) {
    if (!rawQuery) return { tokens: [], cleanText: '', hasPostomatKeyword: false, hasBranchKeyword: false, detectedCity: null };

    let text = rawQuery.trim().replace(/^[\s=+\-*•—–~#№\\\/]+/, '');

    // 0. Склеювання розірваних поштових індексів (Space-separated Postal Code: "79 049" -> "79049")
    text = text.replace(/(\b\d{2})\s+(\d{3}\b)/g, '$1$2');

    // Склеювання маркерів поштоматів (п/м -> пм)
    text = text.replace(/(?<!\p{L})п\/м(?!\p{L})/giu, 'пм');

    // 1. Очищення пунктуації та мусорних символів (дефіси, тире, підкреслення, повтори знаків)
    // Наприклад: "нова пошта --- коломи я 6" -> "нова пошта коломи я 6"
    text = text.replace(/[-_–—~*+=/\\#№!?:;.,]{2,}/g, ' ');
    text = text.replace(/\s+[-_–—~*+=/\\]+\s+/g, ' ');
    text = text.replace(/^[–—_\s~*+=]+|[–—_\s~*+=]+$/g, '');

    // 2. Виправлення клавіатурної розкладки
    text = fixKeyboardLayout(text);

    // 3. Сленгові та помилкові набори
    text = text.replace(/\b(?:retd|rbtd|куев|куєв)\b/gi, 'київ');

    // 4. Розділення склеєних літер та цифр
    text = text.replace(/([А-Яа-яІіЇїЄєA-Za-z])(\d+)/gu, '$1 $2')
               .replace(/(\d+)([А-Яа-яІіЇїЄєA-Za-z])/gu, '$1 $2');

    const hasPostomatKeyword = isPostomatKeyword(text);
    const hasBranchKeyword = /(?<!\p{L})(?:відділення|відділ|вд|склад)(?!\p{L})/iu.test(text);

    const cleanLower = text.toLowerCase().replace(/[^a-zа-яіїєґ0-9\s-]/gi, ' ').replace(/\s+/g, ' ').trim();
    if (!cleanLower) return { tokens: [], cleanText: '', hasPostomatKeyword, hasBranchKeyword, detectedCity: null };

    let rawTokens = cleanLower.split(/\s+/).filter(Boolean);
    let filteredTokens = rawTokens.filter(t => !STOP_WORDS.has(t) && !/^[-_–—]+$/.test(t));
    if (filteredTokens.length === 0) filteredTokens = rawTokens;

    let mergedTokens = [];
    let detectedCity = null;

    // 5. Виправлення розірваних слів (склеювання одиночних літер та частин слів)
    // Наприклад: ["коломи", "я"] -> "коломия", ["о", "деса"] -> "одеса"
    for (let i = 0; i < filteredTokens.length; i++) {
      const cur = filteredTokens[i];
      const next = filteredTokens[i + 1];

      // Якщо токен є скороченням області (наприклад "хмель", "терн", "зп"), зберігаємо його як є і не замінюємо на місто
      if (isOblastToken(cur) && cur !== 'дніпро') {
        mergedTokens.push(cur);
        continue;
      }

      if (next && !/^\d+$/.test(cur) && !/^\d+$/.test(next)) {
        const foundCombined = findSettlementByNameOrFuzzy(cur + ' ' + next) || findSettlementByNameOrFuzzy((cur + next).replace(/-/g, ''));
        if (foundCombined) {
          if (!detectedCity) {
            detectedCity = foundCombined;
            mergedTokens.push(foundCombined.name.toLowerCase());
          } else {
            // Region disambiguation: check if foundCombined is in detectedCity's oblast (e.g. Житомир -> Нові Білокоровичі)
            const oblStem = detectedCity.name.toLowerCase().slice(0, 5);
            const combObl = (foundCombined.oblast || '').toLowerCase();
            if (combObl.includes(oblStem)) {
              detectedCity = foundCombined;
              mergedTokens.push(foundCombined.name.toLowerCase());
            } else {
              mergedTokens.push(cur);
              continue;
            }
          }
          i++; // Пропускаємо наступний склеєний токен
          continue;
        }
      }

      // Якщо слово не склеїлося, перевіряємо нечітке зіставлення одиночного токена
      if (!/^\d+$/.test(cur)) {
        const foundSingle = findSettlementByNameOrFuzzy(cur);
        if (foundSingle) {
          if (!detectedCity) {
            detectedCity = foundSingle;
            mergedTokens.push(foundSingle.name.toLowerCase());
          } else {
            // Малий населений пункт (село/смт) має безумовний пріоритет як цільове місто над містом/райцентром
            const isVillage = foundSingle.type === 'село' || foundSingle.type === 'смт' || foundSingle.type === 'селище';
            const prevIsCity = !detectedCity.type || detectedCity.type === 'місто';

            if (isVillage && prevIsCity) {
              const singleObl = (foundSingle.oblast || '').toLowerCase();
              const oblStem = detectedCity.name.toLowerCase().slice(0, 4);
              const singleRaion = (foundSingle.raion || '').toLowerCase();
              const isCompatible = singleObl.includes(oblStem) || singleRaion.includes(oblStem) ||
                                   (detectedCity.oblast && foundSingle.oblast && detectedCity.oblast === foundSingle.oblast);
              if (isCompatible) {
                detectedCity = foundSingle;
                mergedTokens.push(foundSingle.name.toLowerCase());
                continue;
              }
            }

            // Region disambiguation: check if foundSingle is in detectedCity's oblast
            const oblStem = detectedCity.name.toLowerCase().slice(0, 5);
            const singleObl = (foundSingle.oblast || '').toLowerCase();
            const isRegionalCenter = REGIONAL_CENTERS.has(foundSingle.name.toLowerCase());
            const targetOblastMatches = (detectedCity.oblast || '').toLowerCase().includes(foundSingle.name.toLowerCase().slice(0, 5));
            if (singleObl.includes(oblStem) && !isRegionalCenter) {
              detectedCity = foundSingle;
              mergedTokens.push(foundSingle.name.toLowerCase());
            } else if (isRegionalCenter && targetOblastMatches) {
              // Захист села від поглинання обласним центром: залишаємо село якорем
              mergedTokens.push(foundSingle.name.toLowerCase());
            } else {
              // Primary Settlement Anchor: anchor is already fixed!
              // Do NOT overwrite detectedCity and treat cur as street/other token (e.g. "київ" in "гриців 1 київ")
              mergedTokens.push(cur);
            }
          }
          continue;
        }
      }

      mergedTokens.push(cur);
    }

    // 6. Нормалізація відмінків для кожного токена
    mergedTokens = mergedTokens.map(t => {
      if (/^\d+$/.test(t)) return t;
      return normalizeLocativeCase(t);
    });

    return {
      tokens: mergedTokens,
      cleanText: mergedTokens.join(' '),
      hasPostomatKeyword,
      hasBranchKeyword,
      detectedCity
    };
  }

  // 6. РОЗШИРЕНИЙ NLP ПАРСИНГ ХАОТИЧНИХ МІКРОЗАПИТІВ ОПЕРАТОРІВ
  function parseQuery(rawQuery) {
    if (!rawQuery) {
      return {
        rawQuery: '',
        cleanQuery: '',
        targetBranchNumber: null,
        postalCode: null,
        oblast: null,
        settlement: null,
        didYouMeanText: null,
        facets: { city: null, number: null, oblast: null, raion: null, streetTokens: [], settlementOblast: null }
      };
    }

    // Крок 1. Перемикання розкладки
    let corrected = fixKeyboardLayout(rawQuery.trim().replace(/^[\s=+\-*•—–~#№\\\/]+/, ''));
    const isLayoutFixed = corrected.toLowerCase() !== rawQuery.trim().toLowerCase();

    // Склеювання розірваних поштових індексів ("79 049" -> "79049") та маркерів поштоматів
    corrected = corrected.replace(/(\b\d{2})\s+(\d{3}\b)/g, '$1$2')
                         .replace(/(?<!\p{L})п\/м(?!\p{L})/giu, 'пм');

    // Автоматично розділяємо склеєні літери та цифри (наприклад, «підгайці1» -> «підгайці 1», «київ2» -> «київ 2»)
    corrected = corrected.replace(/([А-Яа-яІіЇїЄєA-Za-z])(\d+)/gu, '$1 $2')
                         .replace(/(\d+)([А-Яа-яІіЇїЄєA-Za-z])/gu, '$1 $2');

    // Видаляємо прийменники на початку або після роздільників (у, в, по, на, біля)
    corrected = corrected.replace(/^(?:у|в|по|на|біля)\s+/iu, '')
                         .replace(/([,;])\s*(?:у|в|по|на|біля)\s+/giu, '$1 ');

    // Крок 2. Виявлення поштомату та номера відділення
    let isPostomat = isPostomatKeyword(corrected);
    let targetBranchNumber = null;

    // 2.1. Пріоритет: Явне зазначення відділення або поштомату
    const explicitBranchMatch = corrected.match(/(?:поштомат|поштомата|поштомати|почтомат|пошт|п\/м|пм|відділення|віділення|відділ|№|#)\s*(?:№|#)?\s*(\b\d{1,6}\b)/iu);
    if (explicitBranchMatch) {
      targetBranchNumber = explicitBranchMatch[1];
      if (parseInt(targetBranchNumber, 10) >= 1000 || isPostomatKeyword(corrected)) {
        isPostomat = true;
      }
    }

    // 2.2. Якщо не знайдено, перевіряємо символ № або #
    if (!targetBranchNumber) {
      const numSignMatch = corrected.match(/(?:№|#)\s*(\b\d{1,6}\b)/iu);
      if (numSignMatch) {
        targetBranchNumber = numSignMatch[1];
        if (parseInt(targetBranchNumber, 10) >= 1000) isPostomat = true;
      }
    }

    // 2.3. Якщо є слово поштомат і є 3-6 значне число
    if (!targetBranchNumber && isPostomat) {
      const anyPostomatNum = corrected.match(/\b\d{3,6}\b/);
      if (anyPostomatNum) {
        targetBranchNumber = anyPostomatNum[0];
      }
    }

    // Крок 3. Поштовий індекс чи номер поштомату (розрізнення за базою індексів)
    let postalCode = null;
    const all5Digits = corrected.match(/\b\d{5}\b/g);
    if (all5Digits) {
      for (let cand of all5Digits) {
        const isKnownPostal = UKRAINE_SETTLEMENTS.some(s => s.postalCodes && s.postalCodes.includes(cand));
        if (isKnownPostal && !isPostomat && cand !== targetBranchNumber) {
          postalCode = cand;
          break;
        }
      }
    }

    // 2.4. Якщо все ще немає номера відділення, шукаємо окремо стоячі цифри
    if (!targetBranchNumber) {
      const standaloneNum = corrected.match(/\b\d{1,6}\b/);
      if (standaloneNum) {
        if (!postalCode || standaloneNum[0] !== postalCode) {
          targetBranchNumber = standaloneNum[0];
          if (parseInt(targetBranchNumber, 10) >= 1000) {
            isPostomat = true;
          }
        }
      }
    }

    // 2.5. Якщо досі не визначено ані індекс, ані номер відділення, будь-яке 5-значне число вважаємо поштоматом
    if (!targetBranchNumber && !postalCode) {
      const any5 = corrected.match(/\b\d{5}\b/);
      if (any5) {
        targetBranchNumber = any5[0];
        isPostomat = true;
      }
    }

    // Крок 4. Виявлення області та району
    const detectedOblast = detectOblast(corrected);
    const detectedRaion = detectRaion(corrected);

    // Крок 5. Виявлення вулиці
    let detectedStreet = null;
    let remForStreet = corrected;

    for (let st of FAMOUS_STREETS) {
      const stRegex = new RegExp(`(?<!\\p{L})${st}(?!\\p{L})`, 'iu');
      if (stRegex.test(remForStreet)) {
        detectedStreet = 'вул. ' + st.split(' ').map(w => w.charAt(0).toUpperCase() + w.slice(1)).join(' ');
        remForStreet = remForStreet.replace(stRegex, ' ');
        break;
      }
    }

    const streetPatternMatch = remForStreet.match(/(?<!\p{L})(?:вул|вулиця|просп|проспект|пл|площа|бульв|бульвар)\.?\s+([А-Яа-яІіЇїЄє\s\d-]+)/iu);
    if (!detectedStreet && streetPatternMatch) {
      detectedStreet = streetPatternMatch[0].trim();
    }

    // Крок 6. Очищення запиту від області, району, службових слів
    let stripped = corrected
      .replace(/(?<!\p{L})(київська|львівська|івано-франківська|тернопільська|дніпропетровська|одеська|харківська|вінницька|полтавська|житомирська|запорізька|миколаївська|черкаська|чернігівська|рівненська|волинська|закарпатська|чернівецька|хмельницька|сумська|кіровоградська|донецька|луганська|херсонська)(?!\p{L})\s*(?:область|обл)?/giu, ' ')
      .replace(/(?<!\p{L})([А-Яа-яІіЇїЄє]+(?:ський|цький|зький|ського|цького|зького))(?!\p{L})\s*(?:район|району|р-н)?/giu, ' ')
      .replace(/(?<!\p{L})(?:нова\s+пошта|нової\s+пошти|укрпошта|укрпошти)(?!\p{L})/giu, ' ')
      .replace(/(?<!\p{L})(?:область|області|обл|район|району|р-н|р-он|смт|селище|село|с|місто|м|відділення|віділення|відділ|поштомат|поштомата|поштомати|почтомат|пошт|п\/м|пм|пошта|вулиця|вул|просп|проспект|бульв|бульвар)(?!\p{L})/giu, ' ')
      .replace(/[№#]/g, ' ')
      .replace(/\b\d+\b/g, ' ');

    if (detectedStreet) {
      const cleanSt = detectedStreet.replace(/^(вул|просп|пл|бульвар)\.?\s+/i, '');
      stripped = stripped.replace(new RegExp(cleanSt, 'gi'), ' ');
    }

    stripped = stripped
      .replace(/[,.-]/g, ' ')
      .replace(/\s+/g, ' ')
      .trim()
      .toLowerCase();

    let matchedSettlement = null;
    let highestScore = 0;

    // 7.0. Інтелектуальна нормалізація токенів за принципом Google
    const norm = normalizeSearchTokens(rawQuery);
    if (norm.detectedCity) {
      matchedSettlement = norm.detectedCity;
      highestScore = 0.98;
    }

    if (!targetBranchNumber) {
      const numTok = norm.tokens.find(t => /^\d{1,6}$/.test(t));
      if (numTok && (!postalCode || numTok !== postalCode)) {
        targetBranchNumber = numTok;
        if (parseInt(targetBranchNumber, 10) >= 1000) {
          isPostomat = true;
        }
      }
    }

    // Крок 7. Пошук населеного пункту з урахуванням відмінків
    if (!matchedSettlement) {
      const normStripped = normalizeLocativeCase(stripped);

      // 7.1. Прямий збіг (назва або аліас)
      if (stripped.length > 0) {
      for (let item of UKRAINE_SETTLEMENTS) {
        if (item.name.toLowerCase() === stripped || item.name.toLowerCase() === normStripped) {
          matchedSettlement = item;
          highestScore = 1.0;
          break;
        }
        for (let alias of item.aliases) {
          if (stripped === alias || normStripped === alias) {
            matchedSettlement = item;
            highestScore = 1.0;
            break;
          }
          const escAlias = alias.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
          if (new RegExp(`(?<!\\p{L})${escAlias}(?!\\p{L})`, 'iu').test(stripped) ||
              new RegExp(`(?<!\\p{L})${escAlias}(?!\\p{L})`, 'iu').test(normStripped)) {
            matchedSettlement = item;
            highestScore = 0.95;
            break;
          }
        }
        if (highestScore === 1.0) break;
      }
    }

    // 7.2. Пошук по токенах (із нормалізацією кожного токена)
    if (!matchedSettlement && stripped.length > 0) {
      const tokens = stripped.split(/\s+/).filter(t => t.length > 1);
      for (let token of tokens) {
        const normTok = normalizeLocativeCase(token);
        for (let item of UKRAINE_SETTLEMENTS) {
          if (item.name.toLowerCase() === token || item.name.toLowerCase() === normTok) {
            matchedSettlement = item;
            highestScore = 0.95;
            break;
          }
          for (let alias of item.aliases) {
            if (token === alias || normTok === alias) {
              matchedSettlement = item;
              highestScore = 0.90;
              break;
            }
          }
          if (matchedSettlement) break;
        }
        if (matchedSettlement) break;
      }
    }

    // 7.3. Нечіткий пошук (Damerau-Levenshtein)
    if (!matchedSettlement && stripped.length >= 3) {
      const words = stripped.split(/\s+/).filter(w => w.length >= 3);
      for (let word of words) {
        const normWord = normalizeLocativeCase(word);
        for (let item of UKRAINE_SETTLEMENTS) {
          if (detectedOblast && item.oblast !== detectedOblast.name) continue;
          for (let alias of item.aliases) {
            const score1 = similarityScore(word, alias);
            const score2 = similarityScore(normWord, alias);
            const score = Math.max(score1, score2);
            if (score > highestScore && score >= 0.70) {
              highestScore = score;
              matchedSettlement = item;
            }
          }
        }
      }
    }
    }

    // 7.5. Формування підказки did-you-mean
    let didYouMeanText = null;
    if (matchedSettlement) {
      const parts = [matchedSettlement.name];
      if (detectedOblast && detectedOblast.name !== matchedSettlement.name) {
        parts.push(`${detectedOblast.name} область`);
      }
      if (targetBranchNumber) {
        parts.push(isPostomat ? `Поштомат №${targetBranchNumber}` : `Відділення №${targetBranchNumber}`);
      }

      const suggestion = parts.join(', ');
      const normalizedRaw = rawQuery.trim().toLowerCase();
      const normalizedSug = suggestion.toLowerCase();
      if (isLayoutFixed || (normalizedRaw !== normalizedSug && highestScore < 0.95)) {
        didYouMeanText = suggestion;
      }
    }

    return {
      rawQuery: rawQuery.trim(),
      cleanQuery: stripped,
      isLayoutFixed,
      targetBranchNumber,
      isPostomat,
      postalCode,
      detectedOblast: detectedOblast ? detectedOblast.name : (matchedSettlement ? matchedSettlement.oblast : null),
      detectedRaion: detectedRaion || (matchedSettlement ? matchedSettlement.raion : null),
      detectedStreet,
      matchedSettlement,
      confidence: highestScore,
      didYouMeanText,
      facets: extractFacets(rawQuery)
    };
  }

